const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('op', {
  platform: process.platform,
  open: () => ipcRenderer.invoke('open'),
  meta: p => ipcRenderer.invoke('meta', p),
  lyrics: t => ipcRenderer.invoke('lyrics', t),
  pathFor: f => webUtils.getPathForFile(f),
  load: () => ipcRenderer.invoke('db:load'),
  save: d => ipcRenderer.invoke('db:save', d),
  ytSearch: q => ipcRenderer.invoke('yt:search', q),
  ytUrl: id => ipcRenderer.invoke('yt:url', id),
  widget: () => ipcRenderer.send('widget'),
  legacyLibrary: () => ipcRenderer.invoke('library:legacy'),
  cacheInfo: () => ipcRenderer.invoke('cache:info'),
  cacheClear: () => ipcRenderer.invoke('cache:clear'),
  session: () => ipcRenderer.invoke('auth:session'),
  login: () => ipcRenderer.invoke('auth:login'),
  guest: () => ipcRenderer.invoke('auth:guest'),
  logout: () => ipcRenderer.invoke('auth:logout'),
  spotifyFetch: l => ipcRenderer.invoke('spotify:fetch', l),
  pickCsv: () => ipcRenderer.invoke('csv:pick'),
  ytMatch: t => ipcRenderer.invoke('yt:match', t),
  coverFetch: t => ipcRenderer.invoke('cover:fetch', t),
  coverLookup: t => ipcRenderer.invoke('cover:lookup', t),
  rpcCfg: c => ipcRenderer.send('rpc:cfg', c),
  rpcAct: a => ipcRenderer.send('rpc:act', a),
  wmove: d => ipcRenderer.send('wmove', d),
  wsize: n => ipcRenderer.send('wsize', n),
  np: s => ipcRenderer.send('np', s),
  ready: () => ipcRenderer.send('ready'),
  cmd: c => ipcRenderer.send('cmd', c),
  onNp: cb => ipcRenderer.on('np', (_, s) => cb(s)),
  onCmd: cb => ipcRenderer.on('cmd', (_, c) => cb(c)),
});
